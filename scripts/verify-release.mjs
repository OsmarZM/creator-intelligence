import {readFile,stat} from "node:fs/promises";
import {createHash} from "node:crypto";
import {createRequire} from "node:module";
import path from "node:path";
const require=createRequire(import.meta.url);
const updaterRequire=createRequire(require.resolve("electron-updater/package.json"));
const yaml=updaterRequire("js-yaml");
const root=process.cwd(),pkg=JSON.parse(await readFile("package.json","utf8"));
const manifest=yaml.load(await readFile("release/latest.yml","utf8"));
if(manifest.version!==pkg.version)throw new Error("Versão do manifesto não corresponde ao projeto.");
const filename=`Creator-Intelligence-Setup-${pkg.version}.exe`;
const item=manifest.files?.find(file=>file.url===filename);
if(!item)throw new Error("Instalador ausente no manifesto.");
const bytes=await readFile(path.join(root,"release",filename));
if(createHash("sha512").update(bytes).digest("base64")!==item.sha512)throw new Error("SHA-512 do instalador não corresponde ao manifesto.");
if(item.size!==bytes.length)throw new Error("Tamanho do instalador não corresponde ao manifesto.");
await stat(path.join(root,"release",filename+".blockmap"));
const update=yaml.load(await readFile("release/win-unpacked/resources/app-update.yml","utf8"));
if(update.provider!=="github"||update.owner!=="OsmarZM"||update.repo!=="creator-intelligence"||update.token)throw new Error("Configuração de atualização inesperada.");
console.log(JSON.stringify({version:pkg.version,filename,size:bytes.length,sha256:createHash("sha256").update(bytes).digest("hex"),sha512:item.sha512,repository:`${update.owner}/${update.repo}`},null,2));
